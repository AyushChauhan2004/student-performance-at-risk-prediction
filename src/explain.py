"""
explain.py
==========
Explainability utilities for the Student Performance & At-Risk Prediction project.

Provides:
  - Logistic Regression coefficient explanations.
  - Random Forest feature importances.
  - Permutation importance (model-agnostic, used for all models).
  - Per-prediction explanation strings for the Streamlit dashboard.

NOTE ON CAUSATION
-----------------
Feature importance values quantify how much each feature contributes to the
model's predictions on average.  They do NOT prove that any feature CAUSES
academic difficulty.  Correlation is not causation.  Conclusions about
individual students must NEVER be made solely on the basis of these values.
"""

from __future__ import annotations

import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.inspection import permutation_importance

import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from preprocessing import FEATURE_COLUMNS

BASE_DIR = Path(__file__).resolve().parent.parent
MODEL_PATH = BASE_DIR / "models" / "student_risk_model.pkl"


def load_pipeline():
    if not MODEL_PATH.exists():
        raise FileNotFoundError(f"Model artifact not found at {MODEL_PATH}.")
    return joblib.load(MODEL_PATH)


def get_feature_importances(pipeline) -> pd.Series:
    """
    Extract feature importances from the classifier inside the pipeline.

    Returns a Series indexed by feature name, sorted descending.
    Works for RandomForest (feature_importances_) and XGBoost.
    For LogisticRegression, uses absolute coefficient values.
    """
    clf = pipeline.named_steps["clf"]
    name = type(clf).__name__

    if hasattr(clf, "feature_importances_"):
        importances = clf.feature_importances_
    elif hasattr(clf, "coef_"):
        importances = np.abs(clf.coef_[0])
    else:
        raise ValueError(f"Cannot extract importances from {name}")

    series = pd.Series(importances, index=FEATURE_COLUMNS)
    return series.sort_values(ascending=False)


def explain_prediction(
    input_values: dict,
    probability: float,
    pipeline,
) -> dict:
    """
    Generate a human-readable explanation for a single prediction.

    Parameters
    ----------
    input_values : dict
        Raw feature values keyed by feature name.
    probability : float
        Model's predicted probability of at_risk = 1.
    pipeline : fitted sklearn Pipeline

    Returns
    -------
    dict with keys:
        risk_band, probability, top_signals, explanation, disclaimer
    """
    # Risk band thresholds (selected using validation data, provisional)
    if probability < 0.35:
        risk_band = "Low Risk"
    elif probability < 0.65:
        risk_band = "Medium Risk"
    else:
        risk_band = "High Risk"

    # Identify strongest contributing signals
    try:
        importances = get_feature_importances(pipeline)
    except Exception:
        importances = pd.Series({f: 1 / len(FEATURE_COLUMNS) for f in FEATURE_COLUMNS})

    # Rank inputs by importance-weighted deviation from "safe" values
    signals = []
    for feat in FEATURE_COLUMNS:
        val = input_values.get(feat, 0)
        imp = importances.get(feat, 0)
        signals.append((feat, val, float(imp)))

    signals.sort(key=lambda x: -x[2])
    top_3 = signals[:3]

    readable = {
        "attendance_percentage": "Attendance",
        "assignment_completion_percentage": "Assignment Completion",
        "previous_assessment_score": "Previous Score",
        "earlier_assessment_score": "Earlier Score",
        "missed_assignments": "Missed Assignments",
        "average_previous_score": "Average Previous Score",
        "performance_trend": "Performance Trend",
        "assessment_period": "Assessment Period",
    }

    top_signals = [
        {"feature": readable.get(f, f), "value": round(v, 2), "importance": round(i, 4)}
        for f, v, i in top_3
    ]

    explanation = (
        f"The model assigned a {probability:.1%} probability of scoring below 40 in "
        f"the next assessment. The most influential input factors were: "
        + ", ".join(
            f"{s['feature']} ({s['value']})" for s in top_signals
        ) + "."
    )

    disclaimer = (
        "HUMAN REVIEW REQUIRED: This prediction is generated by an automated "
        "advisory model trained on synthetic data. It reflects statistical patterns "
        "and is NOT a confirmed outcome. It must NOT be used to punish students, "
        "assign grades, or make any high-stakes academic decision without educator review."
    )

    return {
        "risk_band": risk_band,
        "probability": round(probability, 4),
        "top_signals": top_signals,
        "explanation": explanation,
        "disclaimer": disclaimer,
    }


